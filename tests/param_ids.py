"""One stable parametrize id for a long string value, derived in one place.

Role: tests (shared helper; offline, no I/O, no subprocess)
Reads: nothing
Writes: nothing
Can move funds: no
Mainnet-safe: yes

WHY THIS EXISTS, AND IT IS A GATE DEFECT RATHER THAN A STYLE PREFERENCE.
tests/suite_baseline.tsv is the ship gate: CLAUDE.md's closing section says to diff
the full suite line by line against a recorded baseline rather than comparing failure
counts, and suite_baseline.py does exactly that, keyed on each test's pytest NODE ID.
When a parametrized case's id is generated by pytest rather than stated by us, that
key belongs to pytest, and it changes when pytest changes.

Measured 2026-11-21 in this container, which is where it was found: `suite_baseline.py
check` exited 1 with "SOMETHING IS WORSE than the recorded baseline" and reported
19 DISAPPEARED tests and 27 added, against a tree where the 19 were all present and
passing. Every one of the six files holding them was last committed BEFORE the
baseline was recorded (2026-10-18) and none was modified, so the tests had not moved;
the ids had. The 19 were not the only misreport: 5842 passed, 4 skipped, 0 failed in
the same run, so a reader comparing counts would have seen nothing wrong, and a reader
trusting the gate's verdict would have been told a regression existed.

THE CAUSE, MEASURED RATHER THAN READ OUT OF PYTEST'S SOURCE. A probe parametrizing
one argument over strings of length 96..120 and collecting with --collect-only:

    length  96   the string itself is the id
    length 100   the string itself is the id
    length 101   the id becomes `value4` -- the argument NAME plus its index
    length 120   `value12`

So pytest 9.2.0 uses a string param verbatim up to 100 characters and invents
`<argname><index>` from 101. pytest 8 had no such limit: the baseline carries ids up
to 754 characters, and the longest this suite now collects is 151. requirements-dev.txt
asks for `pytest>=8.0,<10.0` -- a range that spans the change -- so the gate's keys
depended on which pytest inside the declared range happened to be installed, and the
same tree reads as regressed on one machine and clean on another. That is the whole
defect: a gate whose keys are generated by a tool whose behavior varies across the
range the project declares.

THE FIX IS TO STATE THE ID, NOT TO PIN THE TOOL. Pinning pytest exactly would have
been one line and would have stopped the symptom on this box; it would not have stopped
the cause, and rule 19's test for a patch is exactly that. Passing `ids=short_param_id`
makes the id ours at every site where a value can cross 100 characters, so the key is
the same under every pytest in the declared range -- and tests/test_suite_baseline.py
asserts no id component in the RECORDED file exceeds the limit, so a future long value
fails at record time with a message naming this module rather than six weeks later as
a phantom regression.

WHY NOT A BARE TRUNCATION, and why not a bare hash. A truncation alone collides: this
suite's Solana reference vectors share their first 80 characters (one header, one key
order, one blockhash -- they differ in the lamport amount near the END), so head-only
ids would have produced duplicates, which pytest then disambiguates with an index and
we are back to a generated key. A hash alone is stable but unreadable, and rule 14 asks
that pasted output be self-describing a day later: `reference_message3` already failed
that test, and `3f0a9c21` would fail it the same way. So the id is head + digest: the
head says which case a reader is looking at, the digest makes it unique.
"""

from __future__ import annotations

import hashlib
import re

#: The length at and below which pytest 9.2.0 uses a string param as its own id.
#: MEASURED, not read from pytest's source -- the probe is in this module's docstring.
#: A value longer than this gets a generated id, which is the thing to avoid.
PYTEST_ID_LENGTH_LIMIT = 100

#: How much of the value survives into the id. 48 + 2 + 8 = 58 characters, which is
#: comfortably under the limit and leaves room for pytest to join several params with
#: "-" without the joined id crossing it either.
HEAD_CHARS = 48
DIGEST_CHARS = 8

_WHITESPACE = re.compile(r"\s+")


def short_param_id(value: object) -> str | None:
    """A stable id for a long string, or None to let pytest decide.

    None is returned for everything short enough that pytest's own id is already
    stable -- every string of 100 characters or fewer, and every non-string value.
    Returning None rather than an id for those is deliberate: a dict or a tuple gets
    `<argname><index>` from pytest under 8 and under 9 alike, so there is nothing to
    stabilize, and inventing ids for them would churn every id in the baseline for no
    gain. This function therefore changes exactly the ids that were version-dependent.

    The digest is of the FULL value, so two cases sharing a 48-character head still get
    different ids -- which the Solana reference vectors need, as the module docstring
    explains.
    """
    if not isinstance(value, str) or len(value) <= PYTEST_ID_LENGTH_LIMIT:
        return None

    # Whitespace is collapsed because several of these values are prose sentences that
    # wrap across source lines: a newline inside an id gets ascii-escaped to a literal
    # "\n" by pytest, which is stable but unreadable in a pasted failure line.
    flat = _WHITESPACE.sub(" ", value).strip()
    digest = hashlib.sha256(value.encode("utf-8")).hexdigest()[:DIGEST_CHARS]
    return f"{flat[:HEAD_CHARS]}..{digest}"
