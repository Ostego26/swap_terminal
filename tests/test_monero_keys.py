"""Monero address encoding and the shared 2-of-2 spend key, against a real address.

Role: test (read-only)
Reads: nothing on disk; the stagenet address below is embedded
Writes: nothing
Can move funds: no
Mainnet-safe: yes
Live-safe: yes

WHY ONE REAL ADDRESS IS WORTH MORE THAN A HUNDRED SYNTHETIC ONES

Every synthetic case in this file is checked by the same code that produced it, so
a round trip through a wrong-but-consistent encoder passes. STAGENET_ADDRESS was
generated by a real Monero wallet on 2026-09-27 and is bytes this repo did not
produce: decoding it exercises the base58 block decoder, the block-size table, the
body layout, the network byte AND the Keccak-256 checksum together, and all five
have to be right at once for the checksum to match.

That is the whole offline evidence for this file's encoding half, and it is why the
address is here rather than in a fixture nobody reads.
"""

