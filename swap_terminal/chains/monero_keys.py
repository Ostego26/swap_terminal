# Monero's base58 alphabet. Bitcoin's ordering, and it excludes the same four
# ambiguous characters (0, O, I, l) -- but the ENCODING is not Bitcoin's, which is
# the part that catches people. See _decode_block.
MONERO_BASE58_ALPHABET = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"

FULL_BLOCK_BYTES = 8
FULL_BLOCK_CHARS = 11

# How many base58 characters encode a block of n bytes, for n = 1..8. DERIVED, not
# transcribed: it is ceil(log58(2^(8n))) and the derivation is in the test, which
# recomputes the whole table and asserts it equals this one. Written out here
# because the decoder needs the inverse lookup and a loop would obscure it.
#
#     1 byte  -> 2 chars      5 bytes -> 7 chars
#     2 bytes -> 3 chars      6 bytes -> 9 chars
#     3 bytes -> 5 chars      7 bytes -> 10 chars
#     4 bytes -> 6 chars      8 bytes -> 11 chars
ENCODED_BLOCK_CHARS = (0, 2, 3, 5, 6, 7, 9, 10, 11)

PUBLIC_KEY_BYTES = 32
CHECKSUM_BYTES = 4

# One byte of network/kind prefix, then the public spend key, then the public view
# key. 65 bytes, confirmed by decoding a real stagenet address.
STANDARD_BODY_BYTES = 1 + PUBLIC_KEY_BYTES + PUBLIC_KEY_BYTES


@dataclass(frozen=True)
class NetworkPrefix:
    """One address kind on one network, and the TWO GRADES of evidence for its byte.

    Two booleans rather than one `verified`, because the two things they record are
    different and collapsing them would be rule 17's failure in a struct field:

      from_source   the byte was read out of Monero's own cryptonote_config.h.
                    Authoritative for what the software does, and available for every
                    network without running anything.
      from_address  a real address of this kind, produced by a real wallet, was
                    decoded here and its Keccak checksum reproduced. That is evidence
                    about the whole pipeline -- base58 blocks, body layout, checksum
                    -- and not only about one byte.

    `decode_address` reports both in its refusal when an address matches nothing, so a
    reader debugging an address is told exactly which kind of check is missing rather
    than concluding their address is malformed.
    """

    name: str
    network: str
    byte: int
    from_source: bool
    from_address: bool


