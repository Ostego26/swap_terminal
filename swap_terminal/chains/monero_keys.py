_PREFIX_BY_BYTE = {prefix.byte: prefix for prefix in NETWORK_PREFIXES}
_PRIMARY_BY_NETWORK = {
    prefix.network: prefix for prefix in NETWORK_PREFIXES if prefix.name == "primary"
}


class MoneroAddressError(ValueError):
    """A malformed address, a bad checksum, or an address on the wrong network.

    One class for all three because every one of them means "do not send to this",
    and the message says which. A caller that needs to branch on the reason should
    read `decode_address`'s return value on the success path instead -- the network
    is reported there, so "valid but MAINNET" is a normal result and not an error,
    which is what lets a caller refuse it with its own message.
    """


class MoneroKeyError(ValueError):
    """A key share that is not usable: wrong length, non-canonical, or torsion-bearing."""


def keccak256(data: bytes) -> bytes:
    """Keccak-256, the pre-standard padding Monero uses. NOT hashlib.sha3_256.

    Wrapped in one function so there is exactly one place in this tree that
    chooses between the two, and so the choice is named rather than inlined at
    three call sites where a future reader would have to check each one.
    """
    return keccak.new(digest_bits=256, data=data).digest()


def _decode_block(chars: str) -> bytes:
    """One base58 block -> its fixed number of bytes, big-endian.

    MONERO'S BASE58 IS NOT BITCOIN'S, AND THIS FUNCTION IS THE DIFFERENCE.
    Bitcoin base58 treats the whole payload as one big integer, so the output
    length depends on the value and leading zero bytes need separate handling.
    Monero splits the payload into 8-byte blocks, encodes each as its own integer
    into exactly 11 characters, and pads with the alphabet's zero digit -- so
    block boundaries are fixed and a leading zero byte inside a block is carried
    by the padding rather than by a convention.

    The consequence that matters: a Bitcoin base58 decoder run on a Monero address
    produces the wrong bytes, without erroring, for any address with a zero byte
    near a block boundary. It does not fail loudly, which is why the block decode
    is written out here instead of reusing `base58`, a package this repo already
    depends on for the Bitcoin form.
    """
    try:
        size = ENCODED_BLOCK_CHARS.index(len(chars))
    except ValueError:
        raise MoneroAddressError(
            f"a base58 block of {len(chars)} characters is not a valid Monero block "
            f"length; the valid lengths are {ENCODED_BLOCK_CHARS[1:]}"
        ) from None

    value = 0
    for character in chars:
        digit = MONERO_BASE58_ALPHABET.find(character)
        if digit < 0:
            raise MoneroAddressError(
                f"{character!r} is not in Monero's base58 alphabet. Note it omits "
                f"0, O, I and l, and that this is NOT the XRP Ledger alphabet, "
                f"which reorders the same 58 characters"
            )
        value = value * 58 + digit

    if value >= 1 << (8 * size):
        raise MoneroAddressError(
            f"a {len(chars)}-character block decoded to a value too large for its "
            f"{size} bytes -- this is an overlong encoding and a canonical address "
            f"never contains one"
        )
    return value.to_bytes(size, "big")


def _encode_block(chunk: bytes) -> str:
    """The inverse: n bytes -> exactly ENCODED_BLOCK_CHARS[n] characters, zero-padded."""
    width = ENCODED_BLOCK_CHARS[len(chunk)]
    value = int.from_bytes(chunk, "big")
    characters = []
    for _ in range(width):
        value, digit = divmod(value, 58)
        characters.append(MONERO_BASE58_ALPHABET[digit])
    return "".join(reversed(characters))


def base58_encode(payload: bytes) -> str:
    """Monero base58 over 8-byte blocks. The last block may be short."""
    blocks = [
        payload[offset : offset + FULL_BLOCK_BYTES]
        for offset in range(0, len(payload), FULL_BLOCK_BYTES)
    ]
    return "".join(_encode_block(block) for block in blocks)


def base58_decode(text: str) -> bytes:
    """Monero base58 -> bytes. Refuses a final block of an impossible length."""
    if not text:
        raise MoneroAddressError("empty string is not a base58 payload")
    blocks = [
        text[offset : offset + FULL_BLOCK_CHARS]
        for offset in range(0, len(text), FULL_BLOCK_CHARS)
    ]
    return b"".join(_decode_block(block) for block in blocks)


@dataclass(frozen=True)
class MoneroAddress:
    """A decoded address: which network and kind, and the two public keys."""

    address: str
    network: str
    kind: str
    prefix_byte: int
    public_spend_key: bytes
    public_view_key: bytes
    prefix_from_source: bool
    prefix_from_address: bool

    def is_mainnet(self) -> bool:
        return self.network == "mainnet"


def decode_address(address: str) -> MoneroAddress:
    """Decode and CHECK an address: base58, length, prefix, and the Keccak checksum.

    Returning normally does not mean "safe to send to". It means the string is a
    well-formed Monero address and says which network it is on; refusing a mainnet
    address is the caller's decision and `is_mainnet()` is how to make it, because
    a caller that wants to REPORT "this is mainnet" needs the decode to succeed
    first (rule 14: the operator reads the screen, and "MAINNET" is more use than
    "invalid address").
    """
    if not isinstance(address, str):
        raise MoneroAddressError(f"address must be a string, got {type(address).__name__}")

    raw = base58_decode(address.strip())
    if len(raw) < STANDARD_BODY_BYTES + CHECKSUM_BYTES:
        raise MoneroAddressError(
            f"decoded to {len(raw)} bytes, and a standard address is "
            f"{STANDARD_BODY_BYTES + CHECKSUM_BYTES} (1 prefix + 32 spend + 32 view + 4 "
            f"checksum). An integrated address is 8 bytes longer and is not handled here"
        )
    if len(raw) != STANDARD_BODY_BYTES + CHECKSUM_BYTES:
        raise MoneroAddressError(
            f"decoded to {len(raw)} bytes; only the {STANDARD_BODY_BYTES + CHECKSUM_BYTES}-byte "
            f"standard form is handled. An integrated address carries an 8-byte payment ID "
            f"and a swap has no use for one -- the shared address is generated per swap, so "
            f"there is nothing to disambiguate"
        )

    body, checksum = raw[:-CHECKSUM_BYTES], raw[-CHECKSUM_BYTES:]
    computed = keccak256(body)[:CHECKSUM_BYTES]
    if checksum != computed:
        raise MoneroAddressError(
            f"checksum mismatch: the address carries {checksum.hex()} and Keccak-256 of "
            f"its body gives {computed.hex()}. Either a character was mistyped, or the "
            f"address was built with sha3_256 instead of Keccak-256 -- those are "
            f"different functions and Monero uses the second"
        )

    prefix_byte = body[0]
    prefix = _PREFIX_BY_BYTE.get(prefix_byte)
    if prefix is None:
        known = ", ".join(
            f"{candidate.byte}={candidate.network}/{candidate.name}"
            for candidate in NETWORK_PREFIXES
        )
        raise MoneroAddressError(
            f"prefix byte {prefix_byte} is not one this file knows. The checksum VERIFIED, "
            f"so the address is internally consistent and the gap is this table rather than "
            f"your address. All nine bytes here were read out of Monero's own "
            f"cryptonote_config.h: {known}. An integrated address is 8 bytes longer than a "
            f"standard one and is not handled at all, which is the most likely reason to land "
            f"here"
        )

    return MoneroAddress(
        address=address.strip(),
        network=prefix.network,
        kind=prefix.name,
        prefix_byte=prefix_byte,
        public_spend_key=body[1 : 1 + PUBLIC_KEY_BYTES],
        public_view_key=body[1 + PUBLIC_KEY_BYTES :],
        prefix_from_source=prefix.from_source,
        prefix_from_address=prefix.from_address,
    )


def encode_address(network: str, public_spend_key: bytes, public_view_key: bytes) -> str:
    """Build a standard address. `network` is REQUIRED and there is no default.

    No default, on purpose: every other argument in this file can be wrong and
    produce a refusal somewhere, and a defaulted network would silently produce a
    MAINNET address from a test that meant stagenet. The one-word argument is the
    cheapest possible guard against the most expensive possible typo.
    """
    prefix = _PRIMARY_BY_NETWORK.get(network)
    if prefix is None:
        known = ", ".join(sorted(_PRIMARY_BY_NETWORK))
        raise MoneroAddressError(f"unknown network {network!r}; expected one of {known}")
    for name, key in (("spend", public_spend_key), ("view", public_view_key)):
        if len(key) != PUBLIC_KEY_BYTES:
            raise MoneroKeyError(
                f"public {name} key must be {PUBLIC_KEY_BYTES} bytes, got {len(key)}"
            )
        if not is_canonical(key):
            raise MoneroKeyError(
                f"public {name} key is not a canonical ed25519 encoding, so it is not a "
                f"point any wallet will accept"
            )
    body = bytes([prefix.byte]) + public_spend_key + public_view_key
    return base58_encode(body + keccak256(body)[:CHECKSUM_BYTES])


def _checked_share(share: int, name: str) -> int:
    """A private key share must be a non-zero scalar below l, and the value is never quoted.

    Zero is refused separately from out-of-range because a zero share is the one
    value that makes the sum equal the OTHER party's share alone -- so a
    counterparty who can get you to accept zero has the whole key. That is a
    protocol attack rather than a typo, and it deserves its own sentence.
    """
    if not isinstance(share, int):
        raise MoneroKeyError(f"{name} must be an int, got {type(share).__name__}")
    if share == 0:
        raise MoneroKeyError(
            f"{name} is zero. The shared key would then equal the other share alone, so "
            f"one party would hold the whole spend key -- this is refused as a protocol "
            f"violation, not corrected"
        )
    if not 0 < share < GROUP_ORDER:
        # The value is not quoted: it is a spend-key share, and exception text
        # reaches logs and bug reports. A bit length is enough to fix the call.
        raise MoneroKeyError(
            f"{name} must be in [1, l) where l is the ed25519 group order; this one is "
            f"{share.bit_length()} bits and {'negative' if share < 0 else 'at or above l'}"
        )
    return share


def shared_private_spend_key(share_a: int, share_b: int) -> int:
    """s = s_a + s_b mod l -- the key that spends the swapped XMR.

    Neither party may learn this before the swap commits; each holds one share,
    and the adaptor signature on the Gridcoin leg is what leaks the other. This
    function exists for the END of a swap, when one share has been recovered, and
    for tests. It is NOT how the address is built: that is `shared_address`, which
    needs only the public halves, and keeping the two apart is what lets the
    address be computed by a party who holds one share.
    """
    return scalar_add(_checked_share(share_a, "share_a"), _checked_share(share_b, "share_b"))


def _checked_public_share(key: bytes, name: str) -> Point:
    """A public share must be canonical, on the curve, and torsion-free.

    The torsion check is the one that would be tempting to skip and must not be.
    A share with a small-order component lets a counterparty submit several
    distinct encodings that sum to the same nominal key while disagreeing about
    which point was committed to -- the same class of attack the ed25519
    canonicity rules exist for. modules/ed25519_group.is_torsion_free is stricter
    than some libsodium builds' own predicate on exactly this property; see
    tests/test_ed25519_group.py, where an older libsodium accepts an order-2
    component that this one rejects.
    """
    if len(key) != PUBLIC_KEY_BYTES:
        raise MoneroKeyError(f"{name} must be {PUBLIC_KEY_BYTES} bytes, got {len(key)}")
    if not is_canonical(key):
        raise MoneroKeyError(f"{name} is not a canonical ed25519 encoding")
    point = Point.decompress(key)
    if point.is_identity():
        raise MoneroKeyError(
            f"{name} is the identity, which contributes nothing -- the shared key would "
            f"be the other party's alone"
        )
    if not is_torsion_free(point):
        raise MoneroKeyError(
            f"{name} has a small-order torsion component, so several distinct encodings "
            f"agree with it and the share does not pin one point. Refused"
        )
    return point


def shared_public_key(share_a: bytes, share_b: bytes) -> bytes:
    """S = S_a + S_b, as a compressed ed25519 encoding. Both shares fully checked.

    Point addition, and it commutes -- so both parties compute the same byte
    string regardless of which share they call theirs. A test asserts the
    commutativity rather than leaving it to the reader, because the whole protocol
    rests on the two sides agreeing on one address.
    """
    return _checked_public_share(share_a, "share_a").add(
        _checked_public_share(share_b, "share_b")
    ).compress()


def public_key_for_share(share: int) -> bytes:
    """The public half of one private share: share * B, compressed."""
    return scalar_base_mul(_checked_share(share, "share")).compress()


def shared_address(
    network: str,
    spend_share_a: bytes,
    spend_share_b: bytes,
    view_share_a: bytes,
    view_share_b: bytes,
) -> str:
    """The address a GRC<->XMR swap locks its Monero to. A PROPOSAL, not a tested fix.

    Both the spend and the view key are summed. Summing the VIEW key too is what
    lets each party watch for the lock without either being able to spend, and it
    is why there are four arguments rather than two: a shared spend key with one
    party's view key would let that party alone see the funds arrive.

    NOT TESTED AGAINST A CHAIN (rule 16). The arithmetic here is checked -- point
    addition against libsodium, the encoding against a real wallet-generated
    stagenet address -- but that XMR sent to the result is spendable with
    `shared_private_spend_key` of the corresponding private shares has never been
    demonstrated, because this container cannot reach a stagenet
    (docs/monero_stagenet_funding.md). Until it has been, this is a proposal.

    The check that WILL settle it, when a daemon is reachable, is one call:
    monero-wallet-rpc's `validate_address` on the output, then a transfer to it and
    a sweep out with the summed key. `chains/monero.py` already has the first.
    """
    return encode_address(
        network,
        shared_public_key(spend_share_a, spend_share_b),
        shared_public_key(view_share_a, view_share_b),
    )


