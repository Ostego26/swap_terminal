WALLET_NAME = "regwallet"
# An empty password is correct for a throwaway chain and wrong everywhere else.
# It is spelled out rather than defaulted so that nothing here can be copied to a
# wallet that matters without the copier noticing.
WALLET_PASSWORD = ""

PID_FILES = {"monerod": "monerod.pid", "wallet": "monero-wallet-rpc.pid"}


class RegtestError(RuntimeError):
    """A refusal, or a daemon that did not do what it was asked."""


@dataclass(frozen=True)
class Daemon:
    """One spawned process: what to call it, where it listens, where it logs, and the
    handle to ask whether it is still alive.

    These four always travel together -- every caller that has one has all four --
    and ruff's PLR0913 on the seven-argument wait_for_rpc was right that they wanted
    to be one thing. Rule 12: "the fix is to extract the decision so it can be
    called with seeded inputs, not to raise the ceiling." The `process` handle is
    what makes the difference between waiting for a daemon and waiting for a corpse.
    """

    label: str
    port: int
    log_path: Path
    process: subprocess.Popen


def rpc(port: int, method: str, params: dict | None = None, timeout: int = 60) -> dict:
    """One JSON-RPC call to a local monerod or monero-wallet-rpc.

    Errors arrive as HTTP 200 with an `error` member, so the error is read BEFORE
    anything else -- the same shape, and the same trap, as
    swap_terminal/modules/htlc_rpc.py's rpc_result(): calling raise_for_status()
    first discards the reason.
    """
    body = json.dumps(
        {"jsonrpc": "2.0", "id": "0", "method": method, "params": params or {}}
    ).encode()
    # The suppression on the urlopen below is a CHECKED claim (rule 12), and what
    # was checked is this: S310 warns that urlopen follows whatever scheme a URL
    # names, including file:// and custom handlers. Here the scheme and host are
    # literal -- "http://127.0.0.1" -- and the only interpolation is an integer port
    # from argparse, so no caller can choose either. Ruff does not flag the Request
    # constructor, only the call that performs the fetch, so there is exactly one.
    request = urllib.request.Request(
        f"http://127.0.0.1:{port}/json_rpc",
        data=body,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310
            payload = json.loads(response.read())
    except urllib.error.URLError as error:
        raise RegtestError(f"{method} on port {port}: {error}") from error
    if "error" in payload:
        raise RegtestError(f"{method} on port {port}: {payload['error']}")
    result = payload.get("result")
    if not isinstance(result, dict):
        raise RegtestError(f"{method} on port {port}: no `result` object in the reply")
    return result


def port_is_open(port: int) -> bool:
    """Is something already listening? Checked by TRYING it, not by parsing netstat."""
    with socket.socket() as probe:
        probe.settimeout(1.0)
        return probe.connect_ex(("127.0.0.1", port)) == 0


def refuse_dangerous_data_dir(data_dir: Path) -> None:
    """The two refusals that could cost something, checked before anything starts.

    ~/.bitmonero holds the real stagenet and mainnet chains. A regtest daemon
    pointed there would create a `regtest` subdirectory beside them, which is
    probably harmless and is absolutely not worth finding out. And a blockchain
    inside the repository checkout is either committed or gitignored, and both are
    wrong.
    """
    resolved = data_dir.expanduser().resolve()
    bitmonero = (Path.home() / ".bitmonero").resolve()
    if resolved == bitmonero or bitmonero in resolved.parents:
        raise RegtestError(
            f"refusing --data-dir {resolved}: that is inside ~/.bitmonero, where the REAL "
            f"stagenet and mainnet chains live. Pick a directory of its own"
        )
    repository = Path(__file__).resolve().parent
    if resolved == repository or repository in resolved.parents:
        raise RegtestError(
            f"refusing --data-dir {resolved}: a blockchain inside the checkout would have to "
            f"be committed or gitignored, and both are wrong. Pick a directory outside it"
        )


def write_pid(data_dir: Path, which: str, pid: int) -> None:
    """A pid FILE, not a pgrep pattern. Rule 13: a pattern matches what the command
    line happens to look like today, and renaming a script silently orphans it."""
    (data_dir / PID_FILES[which]).write_text(f"{pid}\n")


def process_is_alive(pid: int) -> bool:
    """Is this pid a RUNNING process? A zombie is not, and os.kill(pid, 0) says it is.

    THIS DISTINCTION IS A DEFECT A TEST FOUND, and it is the kind rule 13 is about.
    A killed child whose parent has not called wait() stays in the process table as
    a zombie, and `os.kill(pid, 0)` on a zombie SUCCEEDS -- the pid still exists. So
    the obvious liveness check reports "STILL RUNNING" for a process that is dead
    and merely unreaped, which is exactly the false alarm that teaches an operator
    to stop believing the stop.

    It did not bite in normal use only by luck of process topology: `--run` and
    `--stop` are separate invocations, so by the time `--stop` kills the daemons
    their original parent has exited and init has reaped them. A caller that did
    both in one process -- which tests/test_monero_regtest.py does, deliberately --
    would have seen the false failure. Relying on that topology rather than fixing
    it would be the "I could not find a caller" reasoning rule 2 refuses.

    /proc/<pid>/stat's third field is the state character; 'Z' is a zombie and 'X'
    is dead. Linux-specific, and this repo is Linux-only in the places that matter
    (the daemons, warbot.sh's pgrep patterns). If /proc is unreadable the answer
    falls back to os.kill, which is the conservative direction: it reports alive.
    """
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        # It exists and belongs to somebody else. Alive, and not ours to kill.
        return True
    try:
        stat = Path(f"/proc/{pid}/stat").read_text()
    except OSError:
        return True
    # The comm field is parenthesised and may itself contain spaces and parens, so
    # the state is the first field AFTER the last ')' rather than split()[2].
    tail = stat.rpartition(")")[2].split()
    return not (tail and tail[0] in {"Z", "X"})


def stop_one(console: Console, data_dir: Path, which: str) -> bool:
    """Terminate one recorded process and ASSERT IT IS GONE.

    Rule 13: "a stop that cannot prove it worked is not a stop. Follow it with a
    check that the process is gone, and make the absence the assertion -- not the
    exit code of the kill." process_is_alive() is what makes that assertion
    trustworthy; see its docstring for the zombie case that made it necessary.
    """
    pid_path = data_dir / PID_FILES[which]
    if not pid_path.is_file():
        return console.check(f"{which} stopped", "no pid file", "gone or never started", True)
    try:
        pid = int(pid_path.read_text().strip())
    except ValueError:
        return console.check(f"{which} stopped", "unreadable pid file", "an integer", False)

    # SIGTERM twice with a widening wait, then SIGKILL. The escalation exists
    # because a daemon blocked writing into a full pipe will not act on a SIGTERM
    # handler, and a stop that gives up politely is not a stop.
    for attempt, sig in ((1, signal.SIGTERM), (2, signal.SIGTERM), (3, signal.SIGKILL)):
        if not process_is_alive(pid):
            break
        try:
            os.kill(pid, sig)
        except ProcessLookupError:
            break
        for _ in range(20 * attempt):
            time.sleep(0.25)
            if not process_is_alive(pid):
                break
        if not process_is_alive(pid):
            break

    if process_is_alive(pid):
        return console.check(f"{which} stopped", f"pid {pid} is STILL RUNNING", "absence", False)
    pid_path.unlink(missing_ok=True)
    return console.check(f"{which} stopped", f"pid {pid} is gone", "absence", True)


def log_tail(log_path: Path, lines: int = 25) -> str:
    """The last lines of a daemon's log, for an error message to CARRY rather than
    point at.

    "Check the log in the data directory" is not a diagnostic -- it is homework, and
    it is what this function replaces. Rule 14: state what the number means next to
    the number; the same applies to a failure and its reason.
    """
    try:
        text = log_path.read_text(errors="replace").strip()
    except OSError as error:
        return f"({log_path} could not be read: {error})"
    if not text:
        return f"({log_path} is empty -- the process wrote nothing at all)"
    return "\n".join(f"          | {line}" for line in text.splitlines()[-lines:])


def wait_for_rpc(console: Console, daemon: Daemon, method: str, seconds: int = 60) -> dict:
    """Poll until the daemon answers -- and STOP THE MOMENT IT DIES.

    THE SECOND HALF IS A DEFECT THIS FUNCTION USED TO HAVE. It polled for the full
    sixty seconds regardless, so a wallet that rejected its own command line and
    exited in 40ms produced forty identical progress lines and then "did not answer
    within 60s". That message is true and useless: it describes the symptom of a
    process that was never running, and it is two steps from the cause. Worse, it
    made the operator wait a minute to be told nothing.

    Now the child's exit status is checked every pass, and an exit is reported
    immediately WITH the tail of its log. Rule 14's "announce before, not only
    after" has a corollary: when the thing being waited for is already dead, say so
    instead of continuing to announce waiting.

    The progress lines stay, because a blinking cursor is indistinguishable from a
    hang and the operator's response to a hang is Ctrl-C.
    """
    started = time.monotonic()
    attempt = 0
    while time.monotonic() - started < seconds:
        attempt += 1
        exit_code = daemon.process.poll()
        if exit_code is not None:
            raise RegtestError(
                f"{daemon.label} EXITED with status {exit_code} after "
                f"{time.monotonic() - started:.1f}s -- it never bound port {daemon.port}. Its "
                f"log says:\n{log_tail(daemon.log_path)}"
            )
        try:
            return rpc(daemon.port, method, timeout=5)
        except RegtestError:
            elapsed = time.monotonic() - started
            console.say(
                f"waiting for {daemon.label} on {daemon.port}: attempt {attempt}, "
                f"{elapsed:.1f}s elapsed"
            )
            time.sleep(1.5)
    raise RegtestError(
        f"{daemon.label} is still running but did not answer {method} on port {daemon.port} "
        f"within {seconds}s. Its log says:\n{log_tail(daemon.log_path)}"
    )


def spawn(command: list[str], log_path: Path) -> subprocess.Popen:
    """Start a daemon with its output on disk, so a failure to start is readable.

    Reaped by stop_one() via the pid file written by the caller -- named here
    because rule 13 asks for the reaper to be named AT THE SPAWN SITE.
    """
    handle = log_path.open("ab")
    return subprocess.Popen(  # noqa: S603  a fixed argv this file built from its own arguments
        command, stdout=handle, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL
    )


