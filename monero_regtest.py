#!/usr/bin/env python3
"""Stand up a Monero REGTEST chain, mine to a wallet, make one transfer. No faucet, no network.

Role: file (operator entry point, at the project root per CLAUDE.md rule 10)
Reads: the monerod and monero-wallet-rpc binaries on PATH, and the regtest data
       directory it creates under --data-dir
Writes: a private regtest blockchain and a new wallet, both under --data-dir
        (default ~/xmr-regtest), plus two pid files there. Nothing in the repo,
        nothing in ~/.bitmonero, nothing in the swap database.
Can move funds: ONLY on a private regtest chain it created itself, whose coins
       are generated by this script and exist nowhere else. It refuses to run
       against any other network -- see REFUSALS below, which is the most
       important section in this file.
Mainnet-safe: yes, and it is made safe by construction rather than by care.
       `generateblocks` is gated inside monerod itself:
       src/rpc/core_rpc_server.cpp:1956 returns
       CORE_RPC_ERROR_CODE_REGTEST_REQUIRED unless the nettype is FAKECHAIN, and
       regtest is its own nettype rather than a mode over another one. So the
       central operation here CANNOT reach stagenet or mainnet even if every
       check below were removed.
Live-safe: yes. It touches no swap database, no live wallet and no configured RPC.

WHY THIS EXISTS: THE FAUCET WAS THE CRITICAL PATH AND IT SHOULD NOT HAVE BEEN

Ten field names in chains/monero_transfers.py -- `txid`, `amount`, `address`,
`amounts`, `subaddr_index`, `confirmations`, `type`, `unlock_time`, `locked`,
`double_spend_seen` -- are the only unconfirmed part of the Monero wire format,
and no unit test can check them: a unit test seeds the same shape it asserts.
monero_chain_check.py is the experiment that can, and it needs one incoming
transfer to look at.

For weeks that meant a stagenet faucet. On 2026-09-27 the only responsive faucet
answered "you have reached request limit, please come tomorrow", and
monero_chain_check.py against the operator's stagenet wallet reported 0.0 XMR and
exited 3 (inconclusive) with all ten names marked unconfirmed.

THE FIELD NAMES ARE A PROPERTY OF THE SOFTWARE, NOT OF THE NETWORK. The same
monero-wallet-rpc binary emits the same keys on regtest as on stagenet. So a
regtest transfer confirms them exactly as well, and it takes seconds.

What regtest does NOT replace: a rehearsal against a network with real peers,
real propagation delay and real reorgs. That still wants stagenet. This removes
the faucet from the critical path; it does not make stagenet pointless.

REFUSALS, AND WHY EACH ONE IS HERE

  no --run                  prints the plan and exits. Starting two daemons is
                            not something a bare invocation should do.
  --data-dir inside the     refused. A blockchain under the checkout would be
  repository                gitignored-or-committed, and both are wrong.
  ~/.bitmonero as the       refused by name. That is where the REAL stagenet and
  data dir                  mainnet chains live, and pointing a regtest daemon
                            at them is the one mistake here that could cost
                            something.
  a daemon already on the   refused rather than reused. A daemon this script did
  chosen RPC port           not start is a daemon whose nettype it did not
                            choose, and "probably regtest" is not good enough
                            when the next call mines blocks.
  nettype not FAKECHAIN     refused after asking the daemon, before any mining.
                            get_info reports `nettype`, and this compares it.

EVERY SPAWN HAS A REAPER, NAMED HERE (rule 13)

Two processes: monerod and monero-wallet-rpc. Both get a pid file in the data
directory, both are terminated by `--stop`, and `--stop` asserts their ABSENCE
rather than the exit code of a kill. The same script that starts them is the
script that stops them, which is rule 13's "a spawn and its reap are one change"
at the smallest scale it can be applied.
"""

