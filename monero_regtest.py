def start_daemon(console: Console, args: argparse.Namespace, data_dir: Path) -> None:
    """Step 2: monerod on a private chain, then CONFIRM its nettype before mining."""
    if port_is_open(args.daemon_port):
        raise RegtestError(
            f"something is already listening on {args.daemon_port}. Refusing to reuse it: a "
            f"daemon this script did not start is a daemon whose nettype it did not choose, and "
            f"the next step mines blocks. Run --stop first, or pick another --daemon-port"
        )
    command = [
        args.monerod,
        "--regtest",
        "--offline",
        "--fixed-difficulty", "1",
        "--data-dir", str(data_dir),
        "--rpc-bind-port", str(args.daemon_port),
        "--p2p-bind-port", str(args.p2p_port),
        "--non-interactive",
        "--log-level", "0",
    ]
    console.say(" ".join(command))
    log_path = data_dir / "monerod.log"
    process = spawn(command, log_path)
    write_pid(data_dir, "monerod", process.pid)
    console.say(f"monerod pid {process.pid}, reaped by `--stop` via {PID_FILES['monerod']}")

    info = wait_for_rpc(
        console, Daemon("monerod", args.daemon_port, log_path, process), "get_info"
    )
    nettype = str(info.get("nettype", "(not reported)"))
    console.check("monerod nettype", nettype, REGTEST_NETTYPE, nettype == REGTEST_NETTYPE)
    if nettype != REGTEST_NETTYPE:
        raise RegtestError(
            f"the daemon says nettype={nettype!r}, not {REGTEST_NETTYPE!r}. Refusing to mine. "
            f"This is the check that stands between a mistyped flag and a real network"
        )
    console.check("monerod height at start", info.get("height"), "1 on a fresh chain",
                  isinstance(info.get("height"), int))


def create_wallet(console: Console, args: argparse.Namespace, data_dir: Path) -> str:
    """Step 3: a wallet on this chain, via monero-wallet-rpc's own create_wallet.

    Done over RPC rather than with monero-wallet-cli because the CLI is interactive
    and an interactive prompt in a pasteable block is rule 14's blinking cursor. The
    wallet RPC is started here in --wallet-dir mode, which is the mode that HAS
    create_wallet and open_wallet; it is the same process used for the rest of the run.
    """
    if port_is_open(args.wallet_port):
        raise RegtestError(
            f"something is already listening on {args.wallet_port}. Run --stop first, or pick "
            f"another --wallet-port"
        )
    # NO --regtest HERE, AND THAT WAS A REAL BUG. monero-wallet-rpc does not have
    # that option: `regtest` appears ZERO times in wallet_rpc_server.cpp,
    # wallet2.cpp and simplewallet.cpp (grepped against release-v0.18 on
    # 2026-09-27). Passing it made the wallet reject its own command line and exit
    # instantly, so this script then polled a dead process for sixty seconds and
    # reported a timeout -- a symptom two steps removed from the cause.
    #
    # The authority for this argv is Monero's OWN functional test harness,
    # tests/functional_tests/functional_tests_rpc.py, which starts a wallet against
    # exactly this kind of regtest daemon:
    #
    #   monerod_base = [... "--regtest", "--fixed-difficulty", ...]
    #   wallet_base  = ["monero-wallet-rpc", "--wallet-dir", ..., "--rpc-bind-port",
    #                   ..., "--disable-rpc-login", "--rpc-ssl", "disabled",
    #                   "--daemon-ssl", "disabled", "--log-level", "1",
    #                   "--allow-mismatched-daemon-version"]
    #
    # The daemon gets the nettype flag; the wallet gets none. A regtest chain uses
    # mainnet address prefixes, which is why the wallet needs no nettype at all and
    # why the address printed below decodes as mainnet/primary -- expected, not a
    # fault, and step 3 reports it rather than asserting a guess.
    #
    # --allow-mismatched-daemon-version is carried over from that harness for the
    # same reason it is there: a regtest daemon's version handshake need not match,
    # and refusing to talk to it is not a safety property on a private chain.
    command = [
        args.wallet_rpc,
        "--trusted-daemon",
        "--daemon-address", f"127.0.0.1:{args.daemon_port}",
        "--wallet-dir", str(data_dir),
        "--rpc-bind-port", str(args.wallet_port),
        "--disable-rpc-login",
        "--rpc-ssl", "disabled",
        "--daemon-ssl", "disabled",
        "--allow-mismatched-daemon-version",
        "--log-level", "1",
    ]
    console.say(" ".join(command))
    log_path = data_dir / "monero-wallet-rpc.log"
    process = spawn(command, log_path)
    write_pid(data_dir, "wallet", process.pid)
    console.say(f"wallet rpc pid {process.pid}, reaped by `--stop` via {PID_FILES['wallet']}")

    wait_for_rpc(
        console,
        Daemon("monero-wallet-rpc", args.wallet_port, log_path, process),
        "get_version",
    )

    existing = data_dir / WALLET_NAME
    if existing.is_file():
        console.say(f"{WALLET_NAME} already exists in the data dir; opening it")
        rpc(args.wallet_port, "open_wallet", {"filename": WALLET_NAME, "password": WALLET_PASSWORD})
    else:
        rpc(args.wallet_port, "create_wallet",
            {"filename": WALLET_NAME, "password": WALLET_PASSWORD, "language": "English"})
        console.say(f"created {WALLET_NAME}")

    address = str(rpc(args.wallet_port, "get_address", {"account_index": 0})["address"])
    console.check("wallet primary address", f"{address[:12]}...{address[-6:]}",
                  f"{MONERO_ADDRESS_CHARS} base58 characters",
                  len(address) == MONERO_ADDRESS_CHARS)

    # Decode it with this repo's own decoder, and REPORT rather than assert. Which
    # network byte monerod uses on regtest is not something this session has
    # established (chains/monero_keys.NETWORK_PREFIXES marks stagenet/primary as the
    # only verified entry), so a refusal here would be new information about the
    # prefix table rather than a fault in the wallet. Printing it is how that
    # information gets out; failing on it would be asserting a guess.
    try:
        decoded = decode_address(address)
        console.say(f"chains/monero_keys decodes it as {decoded.network}/{decoded.kind} "
                    f"(prefix byte {decoded.prefix_byte}, checksum verified)")
    except MoneroAddressError as error:
        console.say(f"chains/monero_keys could not decode it: {error}")
        console.say("NOT a failure of this run -- it means regtest uses a prefix byte that")
        console.say("NETWORK_PREFIXES does not list yet. Worth adding, with this as the source.")
    return address


def mine(console: Console, args: argparse.Namespace, address: str) -> int:
    """Step 4: generateblocks to the wallet. THE call that regtest gates.

    src/rpc/core_rpc_server.cpp:1956 returns CORE_RPC_ERROR_CODE_REGTEST_REQUIRED
    unless the nettype is FAKECHAIN, so this line cannot execute against stagenet or
    mainnet. Everything else in this file is belt; this is the braces, and it is in
    monerod rather than here.
    """
    result = rpc(args.daemon_port, "generateblocks",
                 {"amount_of_blocks": args.blocks, "wallet_address": address},
                 timeout=300)
    height = int(result.get("height", 0))
    console.check("height after mining", height, f"at least {args.blocks}", height >= args.blocks)
    console.say(f"{args.blocks} blocks mined; a coinbase unlocks after "
                f"{COINBASE_UNLOCK_BLOCKS}, so {args.blocks - COINBASE_UNLOCK_BLOCKS} are spendable")
    return height


def wait_for_unlocked_balance(console: Console, args: argparse.Namespace, seconds: int = 180) -> int:
    """Step 5: refresh until something is SPENDABLE, not merely present.

    The distinction is the point: `balance` counts locked coinbase outputs and
    `unlocked_balance` does not, so a transfer attempted on the first is refused for
    a reason that reads like a bug. Progress is printed every poll because this is
    the step that can legitimately take a minute.
    """
    started = time.monotonic()
    attempt = 0
    while time.monotonic() - started < seconds:
        attempt += 1
        rpc(args.wallet_port, "refresh")
        balance = rpc(args.wallet_port, "get_balance", {"account_index": 0})
        total = int(balance.get("balance", 0))
        unlocked = int(balance.get("unlocked_balance", 0))
        console.say(f"refresh {attempt}: balance={total} unlocked={unlocked} atomic units "
                    f"({time.monotonic() - started:.1f}s)")
        if unlocked > 0:
            console.check("unlocked balance", unlocked, "greater than 0", True)
            return unlocked
        time.sleep(2.0)
    raise RegtestError(
        f"no UNLOCKED balance after {seconds}s. `balance` may be non-zero while every output is "
        f"still a locked coinbase -- mine more blocks with --blocks"
    )


def make_one_transfer(
    console: Console, args: argparse.Namespace, unlocked: int, miner_address: str
) -> str:
    """Step 6: an ordinary transfer to a second address in the same wallet.

    THIS IS THE STEP THE WHOLE FILE EXISTS FOR, and the reason it is a transfer
    rather than the mining is exact: a coinbase output does NOT appear in
    get_transfers' `in` array. Only a real transfer does, and `in` is where the ten
    field names live. Mining alone would leave monero_chain_check.py reporting the
    same "no `in` key" it reports against an empty stagenet wallet.

    Paying ourselves is deliberate: it needs no second wallet, and the receiving
    subaddress makes `subaddr_index` non-trivial rather than always {0,0}.
    """
    created = rpc(args.wallet_port, "create_address",
                  {"account_index": 0, "label": "regtest-deposit-target"})
    destination = str(created["address"])
    console.say(f"created subaddress at index {created.get('address_index')} to receive")

    # A tenth of what is unlocked, so the fee cannot make the transfer unaffordable.
    amount = max(1, unlocked // 10)
    sent = rpc(args.wallet_port, "transfer",
               {"destinations": [{"amount": amount, "address": destination}],
                "account_index": 0, "get_tx_key": True},
               timeout=180)
    txid = str(sent.get("tx_hash", ""))
    console.check("transfer tx_hash", txid[:16] + "..." if txid else None,
                  f"{TXID_HEX_CHARS} hex characters", len(txid) == TXID_HEX_CHARS)
    console.say(f"sent {amount} atomic units to index {created.get('address_index')}")

    # Two more blocks so the transfer confirms -- an unconfirmed transfer has
    # confirmations=0 and `locked` true, which is a weaker thing to confirm the field
    # names against than a settled one.
    #
    # MINED TO THE PRIMARY ADDRESS, NOT THE SUBADDRESS, AND THAT WAS A BUG. The first
    # version passed `destination` here, which is the subaddress created just above to
    # RECEIVE the transfer, and monerod answered:
    #
    #     code -12  "Mining to subaddress is not supported yet"
    #
    # measured on the operator's host 2026-09-27, after every earlier step had passed.
    # The miner address and the payee address are different roles and the first version
    # conflated them because the same variable was in scope. Nothing about the transfer
    # needed the blocks to be mined anywhere in particular -- they exist only to bury
    # it -- so the primary address is both correct and arbitrary, which is exactly why
    # reusing `destination` looked harmless.
    rpc(args.daemon_port, "generateblocks",
        {"amount_of_blocks": 2, "wallet_address": miner_address}, timeout=120)
    rpc(args.wallet_port, "refresh")

    transfers = rpc(args.wallet_port, "get_transfers", {"in": True, "account_index": 0})
    incoming = transfers.get("in") or []
    console.check("get_transfers `in` entries", len(incoming), "at least 1", len(incoming) >= 1)
    if incoming:
        present = sorted(incoming[0].keys())
        console.say(f"fields on the first incoming transfer: {', '.join(present)}")
    return txid


def run(console: Console, args: argparse.Namespace) -> int:
    data_dir = Path(args.data_dir).expanduser()
    refuse_dangerous_data_dir(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)

    console.banner(f"monero regtest -- private chain in {data_dir}, no network, no faucet")
    console.say("generateblocks is gated to nettype FAKECHAIN inside monerod itself")
    console.say("(src/rpc/core_rpc_server.cpp:1956), so this cannot touch stagenet or mainnet")

    console.step(1, "check the binaries")
    for label, path in (("monerod", args.monerod), ("monero-wallet-rpc", args.wallet_rpc)):
        try:
            version = subprocess.run(  # noqa: S603  a path from argparse, no shell, --version only
                [path, "--version"], capture_output=True, text=True, timeout=30, check=False
            ).stdout.strip().splitlines()
            console.check(f"{label} binary", version[0] if version else None, "a version line",
                          bool(version))
        except (OSError, subprocess.SubprocessError) as error:
            console.check(f"{label} binary", f"{type(error).__name__}: {error}",
                          "a version line", False)
            console.say(
                f"{path!r} did not answer --version. Install Monero's CLI tools, or pass "
                f"--monerod / --wallet-rpc with an explicit path"
            )
            return console.summary()

    console.step(2, "start monerod on a private regtest chain")
    start_daemon(console, args, data_dir)

    console.step(3, "start monero-wallet-rpc and create a wallet on that chain")
    address = create_wallet(console, args, data_dir)

    console.step(4, f"mine {args.blocks} blocks to that wallet")
    mine(console, args, address)

    console.step(5, "refresh until a coinbase output has UNLOCKED")
    unlocked = wait_for_unlocked_balance(console, args)

    console.step(6, "make ONE ordinary transfer -- a coinbase does not appear in `in`")
    make_one_transfer(console, args, unlocked, address)

    console.step(7, "what to run next")
    console.say(f"python3 monero_chain_check.py --host 127.0.0.1 --port {args.wallet_port}")
    console.say("that is the experiment: it reports which of the ten transfer field names")
    console.say("a real wallet actually used, and exits 3 if it still cannot tell")
    console.say("")
    console.say(f"when finished:  python3 monero_regtest.py --stop --data-dir {data_dir}")
    console.say("the daemons stay up on purpose -- monero_chain_check.py needs the wallet rpc")

    return console.summary()


def main() -> int:
    args = build_parser().parse_args()
    console = Console(total_steps=7)

    if args.stop:
        data_dir = Path(args.data_dir).expanduser()
        console.banner(f"stopping what --run started in {data_dir}")
        console.step(1, "terminate both daemons and assert their ABSENCE")
        for which in ("wallet", "monerod"):
            stop_one(console, data_dir, which)
        console.say(f"the chain and wallet are left in place; delete {data_dir} to reclaim it")
        return console.summary()

    if not args.run:
        print_plan(console, args)
        return 0

    try:
        return run(console, args)
    except RegtestError as error:
        console.check("run", f"{error}", "no refusal", False)
        console.say("")
        console.say("the daemons may still be running. Stop them with:")
        console.say(f"  python3 monero_regtest.py --stop --data-dir {args.data_dir}")
        return console.summary()


if __name__ == "__main__":
    sys.exit(main())
